// Maintains the prebuilt native library table used by hook/build.dart.
// Run from the package root after `flutter pub get`:
//
//   dart --packages=.dart_tool/package_config.json tool/prebuilt.dart <command>
//
//   tag    Print the release tag for the current Rust sources (used by CI).
//   sync   Download every library from that release and write
//          hook/prebuilt.g.dart.
//
// `dart run` would run this package's build hook first, which fails while the
// table is out of date, so the VM is invoked directly.

import 'dart:io';

import 'package:crypto/crypto.dart';

import '../hook/build.dart' show library;
import '../hook/prebuilt.dart';

Future<void> main(List<String> args) async {
  final root = Platform.script.resolve('../');
  final (hash, _) =
      computeCrateHash(Directory.fromUri(root.resolve(library.cratePath)));

  switch (args) {
    case ['tag']:
      stdout.writeln(library.releaseTag(hash));
    case ['sync']:
      final table = StringBuffer();
      for (final triple in library.triples) {
        final uri = library.downloadUri(hash, triple);
        final bytes = await download(uri);
        stdout.writeln('${library.assetFileName(triple)}  ${bytes.length}');
        table.writeln("  '$triple': '${sha256.convert(bytes)}',");
      }
      File.fromUri(root.resolve('hook/prebuilt.g.dart')).writeAsStringSync('''
// Generated by tool/prebuilt.dart sync. Do not edit.

const prebuiltCrateHash = '$hash';

const prebuiltSha256 = <String, String>{
$table};
''');
    default:
      stderr.writeln('Usage: tool/prebuilt.dart <tag|sync>');
      exitCode = 64;
  }
}
